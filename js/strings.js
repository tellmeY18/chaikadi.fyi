export function t(key, ...args) {
  const value = en[key];
  if (value === undefined) throw new Error(`Missing UI string: ${key}`);
  return typeof value === 'function' ? value(...args) : value;
}
export function money(value, currency = 'Rs') {
  const prefix = currency === '₹' || /^[$€£¥]$/.test(currency) ? currency : `${currency} `;
  return prefix + (value / 100).toLocaleString('en-IN', { minimumFractionDigits: value % 100 ? 2 : 0, maximumFractionDigits: 2 });
}
